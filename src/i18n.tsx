type Translations = typeof dict.id;
type Key = keyof Translations;

function interpolate(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.split(`{${k}}`).join(String(v)),
    str
  );
}

// ── Context ────────────────────────────────────────────────────────────────────

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<LangCtx>({
  lang: "id",
  setLang: () => {},
  t: (k) => k,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("ac-lang");
    return saved === "en" ? "en" : "id";
  });

  function setLang(l: Lang) {
    setLangState(l);
    localStorage.setItem("ac-lang", l);
  }

  function t(key: Key, vars?: Record<string, string | number>): string {
    const str = (dict[lang] as Translations)[key] ?? (dict.id as Translations)[key] ?? key;
    return interpolate(str as string, vars);
  }

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}
